// Builds the third-party licence notices from the packages actually installed, so the list is read from the files, not typed from memory.
//   node tools/licences.mjs            writes THIRD-PARTY-NOTICES.txt, public/third-party-notices.txt and docs/data/third-party.json
// Lists every package in the production dependency tree (what ships or could ship), then the support files copied by tools/copy-vendor.mjs.
import { execSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const tree = JSON.parse(execSync("npm ls --omit=dev --all --json --long", { encoding: "utf8", maxBuffer: 1 << 28, stdio: ["ignore", "pipe", "ignore"] }));
const seen = new Map();
(function walk(deps) {
  for (const [name, info] of Object.entries(deps ?? {})) {
    if (info.path && !seen.has(info.path)) {
      seen.set(info.path, { name, version: info.version });
      walk(info.dependencies);
    }
  }
})(tree.dependencies);

const rows = [];
for (const [path, { name, version }] of seen) {
  const pj = JSON.parse(readFileSync(join(path, "package.json"), "utf8"));
  let licence = pj.license ?? (Array.isArray(pj.licenses) ? pj.licenses.map((l) => l.type).join(" OR ") : pj.licenses?.type) ?? "UNKNOWN";
  if (typeof licence === "object") licence = licence.type ?? "UNKNOWN";
  const files = readdirSync(path).filter((f) => /^(licen[cs]e|copying|notice)/i.test(f));
  const text = files.map((f) => readFileSync(join(path, f), "utf8").trim()).join("\n\n");
  rows.push({ name, version, licence, homepage: pj.homepage ?? pj.repository?.url ?? "", text, files });
}
rows.sort((a, b) => a.name.localeCompare(b.name));

// Files copied by tools/copy-vendor.mjs, with the licence files that travel with them.
const vendor = [
  { name: "PDF.js standard fonts (Foxit)", from: "pdfjs-dist", licence: "PDFium BSD-style", file: "node_modules/pdfjs-dist/standard_fonts/LICENSE_FOXIT" },
  { name: "PDF.js JBIG2 decoder (wasm)", from: "pdfjs-dist", licence: "see file", file: "node_modules/pdfjs-dist/wasm/LICENSE_JBIG2" },
  { name: "PDF.js OpenJPEG decoder (wasm)", from: "pdfjs-dist", licence: "BSD-2-Clause", file: "node_modules/pdfjs-dist/wasm/LICENSE_OPENJPEG" },
  { name: "PDF.js colour management (qcms, wasm)", from: "pdfjs-dist", licence: "MIT", file: "node_modules/pdfjs-dist/wasm/LICENSE_QCMS" },
  { name: "PDF.js ICC profile", from: "pdfjs-dist", licence: "CC0-1.0", file: "node_modules/pdfjs-dist/iccs/LICENSE" },
  { name: "Tesseract worker bundle", from: "tesseract.js", licence: "see file", file: "node_modules/tesseract.js/dist/worker.min.js.LICENSE.txt" },
].map((v) => ({ ...v, text: existsSync(v.file) ? readFileSync(v.file, "utf8").trim() : "(file not found)" }));

mkdirSync("docs/data", { recursive: true });
writeFileSync("docs/data/third-party.json", JSON.stringify({ packages: rows.map(({ text, files, ...r }) => ({ ...r, hasLicenceFile: files.length > 0 })), vendor: vendor.map(({ text, ...v }) => v) }, null, 2));

const out = [];
out.push("THIRD-PARTY NOTICES FOR EBON");
out.push("Ebon itself is MIT licensed (see LICENSE). It includes or loads the software below, each under its own licence.");
out.push("Generated by tools/licences.mjs from the installed packages.\n");
for (const r of rows) {
  out.push("=".repeat(78));
  out.push(`${r.name} ${r.version}   licence: ${r.licence}`);
  if (r.homepage) out.push(r.homepage);
  out.push("=".repeat(78));
  out.push(r.text || "(No licence file ships in this package. The licence named above comes from its package.json.)");
  out.push("");
}
for (const v of vendor) {
  out.push("=".repeat(78));
  out.push(`${v.name}   (supplied with ${v.from})`);
  out.push("=".repeat(78));
  out.push(v.text);
  out.push("");
}
const txt = out.join("\n");
writeFileSync("THIRD-PARTY-NOTICES.txt", txt);
mkdirSync("public", { recursive: true });
writeFileSync("public/third-party-notices.txt", txt);
const counts = {};
for (const r of rows) counts[r.licence] = (counts[r.licence] ?? 0) + 1;
console.log(`${rows.length} packages`, counts);
for (const r of rows) if (!r.text) console.log("  no licence file:", r.name, r.licence);
